#!/usr/bin/env python3
"""
Build db/init/02_seed.sql for the HUD from:
  - sector_totals.json              {"SECTOR 0X // NAME — TAGLINE": [file_count, size]}
  - SEC_SHINRADOOM_SECTOR_MAP.csv   columns: Sector, Top Folder, Folder Path, File, Type, Size MB

Only rollups by sector and top folder are written. No file names and no folder
paths below the top folder are ever emitted. Top folders whose names look
sensitive (ids, licenses, medical, tax, bank, resume, ...) are relabelled
"Restricted folder" so nothing personal reaches the public feed.

Usage (from the hud/ directory):
  python3 tools/build_seed.py --totals ../sector_totals.json \
      --csv ../SEC_SHINRADOOM_SECTOR_MAP.csv --out db/init/02_seed.sql \
      --preview tools/seed_preview.json
"""
import argparse
import csv
import json
import re
import sys
from collections import OrderedDict, defaultdict

SENSITIVE = re.compile(
    r"(\bssn\b|social.?security|passport|driver'?s?.?licen[cs]e|\blicen[cs]e\b|\bid.?card\b|"
    r"\bstate.?id\b|birth.?cert|medical|medicaid|medicare|health|hospital|diagnos|prescript|"
    r"\brx\b|\btax(es)?\b|\bw-?2\b|\b1099\b|\birs\b|bank|statement|routing|account.?num|"
    r"credit.?card|paystub|pay.?stub|payroll|resume|résumé|\bcv\b|lease|insurance|"
    r"court|legal|immigration|visa\b)",
    re.IGNORECASE,
)

SECTOR_RE = re.compile(r"^(SECTOR\s+\d+)\s*//\s*(.+?)(?:\s*\u2014\s*|\s+-\s+)(.+)$")


def sql_str(value):
    if value is None:
        return "NULL"
    s = str(value)
    s = s.replace("\\", "\\\\").replace("'", "''").replace("\n", "\\n").replace("\r", "")
    return "'" + s + "'"


def split_sector(full):
    m = SECTOR_RE.match(full.strip())
    if not m:
        return full.strip()[:32], full.strip(), ""
    return m.group(1).upper(), m.group(2).strip(), m.group(3).strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--totals", required=True)
    ap.add_argument("--csv", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--preview", required=True)
    a = ap.parse_args()

    with open(a.totals, encoding="utf-8") as f:
        totals = json.load(f)

    roll = defaultdict(lambda: [0, 0.0])
    csv_sector = defaultdict(lambda: [0, 0.0])
    sensitive_rows = 0
    with open(a.csv, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            sec = row["Sector"].strip()
            top = (row["Top Folder"] or "").strip() or "(root)"
            try:
                mb = float(row["Size MB"] or 0)
            except ValueError:
                mb = 0.0
            if SENSITIVE.search(row.get("File") or "") or SENSITIVE.search(row.get("Folder Path") or ""):
                sensitive_rows += 1  # counted, never named
            roll[(sec, top)][0] += 1
            roll[(sec, top)][1] += mb
            csv_sector[sec][0] += 1
            csv_sector[sec][1] += mb

    sectors = sorted(totals.keys(), key=lambda s: split_sector(s)[0])
    checks = []
    out = []
    out.append("-- Generated by tools/build_seed.py. Do not hand-edit; re-run the script.")
    out.append("-- Rollups by sector and top folder only. No file names are included.")
    out.append("SET NAMES utf8mb4;")
    out.append("START TRANSACTION;")
    out.append("")
    out.append("INSERT INTO variants (id, slug, title, subtitle, disclaimer, sort_order) VALUES")
    out.append(" (1, 'sectors', '7 Sectors', 'Drive archive map: sector and top-folder rollups', NULL, 1),")
    out.append(" (2, 'companies', '3 Companies', 'Open-knowledge preservation watch', "
               "'Independent fan dashboard. Not affiliated with or endorsed by Wikimedia, Mozilla, or the Linux Foundation.', 2);")
    out.append("")

    preview = OrderedDict(variant="sectors", sectors=[])
    org_id = 0
    item_rows = []
    org_rows = []
    for i, sec in enumerate(sectors, start=1):
        org_id += 1
        code, name, tagline = split_sector(sec)
        jcount, jsize = totals[sec]
        ccount, cmb = csv_sector.get(sec, [0, 0.0])
        checks.append(dict(sector=code, json_files=jcount, csv_files=ccount,
                           json_size=jsize, csv_mb=round(cmb, 2),
                           ratio_csv_mb_to_json=round(cmb / jsize, 1) if jsize else None))
        org_rows.append("({id}, 1, {slug}, {code}, {name}, {tag}, NULL, NULL, NULL, {fc}, {mb}, {rep}, {so})".format(
            id=org_id, slug=sql_str(code.lower().replace(" ", "-")), code=sql_str(code), name=sql_str(name),
            tag=sql_str(tagline), fc=int(jcount), mb="%.2f" % cmb, rep="%.2f" % float(jsize), so=i))
        sp = OrderedDict(code=code, name=name, tagline=tagline, file_count=int(jcount),
                         size_mb=round(cmb, 2), top_folders=[])
        tops = sorted([(k[1], v) for k, v in roll.items() if k[0] == sec], key=lambda t: -t[1][0])
        for j, (top, (cnt, mb)) in enumerate(tops, start=1):
            label = "Restricted folder" if SENSITIVE.search(top) else top
            item_rows.append("({oid}, 1, 'folder', {label}, NULL, {fc}, {mb}, NULL, {so})".format(
                oid=org_id, label=sql_str(label[:190]), fc=cnt, mb="%.2f" % mb, so=j))
            sp["top_folders"].append(OrderedDict(label=label, file_count=cnt, size_mb=round(mb, 2)))
        preview["sectors"].append(sp)

    # ---- 3 Companies (independent fan/preservation dashboard) -------------
    companies = [
        dict(slug="wikimedia", code="ORG 01", name="Wikimedia Foundation",
             tagline="Free knowledge, in perpetuity",
             mission=("The mission of the Wikimedia Foundation is to empower and engage people around the world "
                      "to collect and develop educational content under a free license or in the public domain, "
                      "and to disseminate it effectively and globally."),
             volunteer=("Edit or fact-check Wikipedia articles; upload freely licensed media to Wikimedia Commons; "
                        "add structured data on Wikidata; transcribe public-domain texts on Wikisource; "
                        "join a local chapter or user group; report bugs and help with MediaWiki development."),
             notes=("Mission statement quoted from wikimediafoundation.org/about/mission (checked Nov 2026). "
                    "The Foundation states it will keep useful information from its projects available on the "
                    "internet free of charge, in perpetuity. Database dumps are published for offline mirrors."),
             projects=["Wikipedia", "Wikimedia Commons", "Wikidata", "Wiktionary", "Wikisource", "MediaWiki"],
             links=[("Mission", "https://wikimediafoundation.org/about/mission/"),
                    ("Get involved", "https://wikimediafoundation.org/participate/"),
                    ("Wikimedia projects", "https://wikimediafoundation.org/what-we-do/wikimedia-projects/"),
                    ("Database dumps", "https://dumps.wikimedia.org/")]),
        dict(slug="mozilla", code="ORG 02", name="Mozilla",
             tagline="The internet as a global public resource",
             mission=("Mozilla Manifesto, principle 2: the internet is a global public resource that must remain "
                      "open and accessible. The Manifesto (2007) and the Pledge for a Healthy Internet (2017) "
                      "guide Mozilla's work."),
             volunteer=("Answer questions on Mozilla Support; translate Firefox and other products in Pontoon; "
                        "file and triage bugs in Bugzilla; improve MDN Web Docs; contribute to Mozilla's "
                        "open-source code on GitHub."),
             notes=("Principle text quoted from mozilla.org/about/manifesto (checked Nov 2026). "
                    "MDN Web Docs is an openly licensed reference for web technologies; its content is "
                    "maintained in public repositories."),
             projects=["Firefox", "Thunderbird", "MDN Web Docs", "Mozilla Foundation"],
             links=[("Manifesto", "https://www.mozilla.org/en-US/about/manifesto/"),
                    ("Get involved", "https://www.mozilla.org/en-US/contribute/"),
                    ("Localize (Pontoon)", "https://pontoon.mozilla.org/"),
                    ("File a bug", "https://bugzilla.mozilla.org/"),
                    ("MDN Web Docs", "https://developer.mozilla.org/")]),
        dict(slug="linux-foundation", code="ORG 03", name="Linux Foundation",
             tagline="A neutral home for open technology",
             mission=("The Linux Foundation provides a neutral, trusted hub for developers to code, manage, and "
                      "scale open technology projects."),
             volunteer=("Contribute code, docs, or reviews to a hosted project; take free LF Education courses; "
                        "join an open working group; apply to or mentor through LFX Mentorship; "
                        "help triage issues in the projects you use."),
             notes=("Mission line quoted from linuxfoundation.org/about (checked Nov 2026). "
                    "The LF is a 501(c)(6) non-profit that hosts many projects under neutral governance."),
             projects=["Linux kernel (supported via the LF)", "Kubernetes (CNCF)", "Node.js (OpenJS Foundation)",
                       "OpenSSF", "PyTorch Foundation"],
             links=[("About", "https://www.linuxfoundation.org/about"),
                    ("All projects", "https://www.linuxfoundation.org/projects"),
                    ("LF Education", "https://training.linuxfoundation.org/"),
                    ("LFX", "https://lfx.linuxfoundation.org/"),
                    ("kernel.org", "https://www.kernel.org/")]),
    ]
    cpreview = OrderedDict(variant="companies", orgs=[])
    for i, c in enumerate(companies, start=1):
        org_id += 1
        org_rows.append("({id}, 2, {slug}, {code}, {name}, {tag}, {mis}, {vol}, {notes}, 0, 0.00, NULL, {so})".format(
            id=org_id, slug=sql_str(c["slug"]), code=sql_str(c["code"]), name=sql_str(c["name"]),
            tag=sql_str(c["tagline"]), mis=sql_str(c["mission"]), vol=sql_str(c["volunteer"]),
            notes=sql_str(c["notes"]), so=i))
        for j, p in enumerate(c["projects"], start=1):
            item_rows.append("({oid}, 2, 'project', {l}, NULL, 0, 0.00, NULL, {so})".format(
                oid=org_id, l=sql_str(p), so=j))
        for j, (lab, url) in enumerate(c["links"], start=1):
            assert url.startswith("https://")
            item_rows.append("({oid}, 2, 'link', {l}, NULL, 0, 0.00, {u}, {so})".format(
                oid=org_id, l=sql_str(lab), u=sql_str(url), so=100 + j))
        cpreview["orgs"].append(OrderedDict(name=c["name"], projects=c["projects"],
                                            links=[dict(label=l, url=u) for l, u in c["links"]]))

    out.append("INSERT INTO sectors_or_orgs (id, variant_id, slug, code, name, tagline, mission, volunteer_help, "
               "preservation_notes, file_count, size_mb, reported_size, sort_order) VALUES")
    out.append(",\n".join(" " + r for r in org_rows) + ";")
    out.append("")
    out.append("INSERT INTO items (org_id, variant_id, kind, label, detail, file_count, size_mb, url, sort_order) VALUES")
    out.append(",\n".join(" " + r for r in item_rows) + ";")
    out.append("")

    total_files = sum(int(v[0]) for v in totals.values())
    total_mb = sum(v[1] for v in csv_sector.values())
    biggest = max(sectors, key=lambda s: totals[s][0])
    events = [
        (1, None, "ok", "Archive map online: %d sectors indexed, %s files." % (len(sectors), format(total_files, ","))),
        (1, None, "info", "Rollups cover sector and top folder only. File names are not published."),
        (1, None, "info", "Largest sector by file count: %s." % split_sector(biggest)[0]),
        (1, None, "info", "Total mapped size: %s MB." % format(round(total_mb), ",")),
        (2, None, "ok", "Preservation watch online: 3 open-knowledge organizations tracked."),
        (2, None, "info", "Independent fan dashboard. Not affiliated with or endorsed by Wikimedia, Mozilla, or the Linux Foundation."),
        (2, None, "info", "Mission statements quoted from each organization's official site, checked Nov 2026."),
    ]
    # Stagger timestamps so the ticker shows the first line of each variant as newest.
    out.append("INSERT INTO status_events (variant_id, org_id, level, message, event_at) VALUES")
    out.append(",\n".join(" (%d, NULL, %s, %s, NOW() - INTERVAL %d MINUTE)" % (v, sql_str(l), sql_str(m), n)
                           for n, (v, _, l, m) in enumerate(events)) + ";")
    out.append("")
    out.append("COMMIT;")

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")

    report = OrderedDict(
        totals_check=checks,
        csv_rows=sum(v[0] for v in csv_sector.values()),
        json_total_files=total_files,
        csv_total_mb=round(total_mb, 2),
        sensitive_looking_rows_not_named=sensitive_rows,
        top_folder_rollups=len(roll),
        preview_sectors=preview,
        preview_companies=cpreview,
    )
    with open(a.preview, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    json.load(open(a.preview, encoding="utf-8"))  # validate JSON round-trip
    print(json.dumps(report["totals_check"], indent=1))
    print("csv_rows", report["csv_rows"], "json_total_files", total_files,
          "sensitive_rows_counted", sensitive_rows, "rollups", len(roll))


if __name__ == "__main__":
    sys.exit(main())
